"""From PyTorch to the Arduino: a cost model for the microcontroller and the
generator of ``arduino/gesture_classifier/model_data.h``.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from datetime import datetime
from pathlib import Path

import numpy as np
import torch

from . import config as C
from .models import MLP, count_macs, count_params
from .quantization import QuantMLP, int8_forward, int8_model_bytes

# Very rough cost of one multiply-accumulate in a plain C loop on the
# Cortex-M4F (load weight + load input + multiply-add + loop overhead).
# Measure the real number on your board (the sketch prints it)!
CYCLES_PER_MAC = 4


def mcu_cost(model: MLP, int8: bool = False) -> dict:
    """Flash, RAM and time estimates for running ``model`` on the Nano 33 BLE Sense."""
    params, macs = count_params(model), count_macs(model)
    weight_bytes = params * (1 if int8 else 4)
    if int8:  # biases are int32 and every neuron gets a float32 multiplier
        n_neurons = sum(model.sizes[1:])
        weight_bytes = (params - n_neurons) + 8 * n_neurons
    act_bytes = (model.sizes[0] + 2 * max(model.sizes[1:])) * (1 if int8 else 4)
    return {
        "params": params,
        "MACs": macs,
        "flash_KB": weight_bytes / 1024,
        "flash_%": 100 * weight_bytes / C.MCU_FLASH_BYTES,
        "RAM_KB": act_bytes / 1024,
        "est_ms": macs * CYCLES_PER_MAC / C.MCU_CLOCK_HZ * 1e3,
    }


def cost_table(models: dict[str, tuple[MLP, bool, float]]) -> str:
    """Pretty table. ``models`` maps a name to ``(model, is_int8, test_accuracy)``."""
    head = f"{'model':<34}{'acc':>7}{'params':>9}{'MACs':>9}{'flash KB':>10}{'est. ms':>9}"
    lines = [head, "-" * len(head)]
    for name, (m, int8, acc) in models.items():
        c = mcu_cost(m, int8)
        lines.append(f"{name:<34}{acc:>7.3f}{c['params']:>9,}{c['MACs']:>9,}"
                     f"{c['flash_KB']:>10.1f}{c['est_ms']:>9.2f}")
    return "\n".join(lines)


