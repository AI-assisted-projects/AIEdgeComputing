def device_features(raw_window: np.ndarray, mean: np.ndarray, std: np.ndarray) -> np.ndarray:
    """Exactly what the board computes: float32 ``(raw - mean) / std``, flattened."""
    raw = np.asarray(raw_window, dtype=np.float32)
    return ((raw - mean.astype(np.float32)) / std.astype(np.float32)).reshape(-1).astype(np.float32)


def _c_float(v) -> str:
    """A C float literal that round-trips exactly (9 significant digits)."""
    s = f"{float(v):.9g}"
    if not any(ch in s for ch in ".en"):
        s += ".0"                      # "-4" -> "-4.0" (C has no "-4f")
    return s + "f"


def _c_array(ctype: str, name: str, values, per_line: int = 12) -> str:
    vals = np.asarray(values).ravel()
    items = [_c_float(v) if ctype == "float" else str(int(v)) for v in vals]
    rows = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    body = ",\n  ".join(rows)
    return f"static const {ctype} {name}[{len(vals)}] = {{\n  {body}\n}};\n"


def write_model_header(qmodel: QuantMLP, data, path: str | Path | None = None,
                       test_index: int | None = None) -> Path:
    """Write ``model_data.h``: settings, normalization, int8 + float weights, self-test.

    The float weights are those of the network inside ``qmodel`` (after QAT),
    so you can compare float vs int8 on the board with one ``#define``.
    """
    path = Path(path or C.CLASSIFIER_SKETCH_DIR / "model_data.h")
    mlp: MLP = qmodel.mlp
    q = qmodel.to_int8()
    sizes = mlp.sizes
    n_layers = len(sizes) - 1

    # A self-test sample: a test gesture the int8 model classifies correctly.
    feats_all = np.stack([device_features(w, data.channel_mean, data.channel_std) for w in data.raw_test])
    int8_logits_all = int8_forward(q, feats_all)
    if test_index is None:
        ok = np.flatnonzero(int8_logits_all.argmax(1) == data.y_test.numpy())
        test_index = int(ok[0]) if len(ok) else 0
    test_raw = data.raw_test[test_index].astype(np.float32)
    test_logits_int8 = int8_logits_all[test_index]
    mlp.eval()
    with torch.no_grad():
        test_logits_float = mlp(torch.from_numpy(feats_all[test_index:test_index + 1]))[0].numpy()

    L = []
    L.append("// model_data.h -- AUTO-GENERATED by aiedge/export.py (notebook 05). Do not edit.\n"
             f"// Generated {datetime.now():%Y-%m-%d %H:%M} from {data.source} data.\n"
             f"// Network: {' -> '.join(map(str, sizes))}  (ReLU between layers)\n"
             f"// int8 model: {int8_model_bytes(q)} bytes of weights/biases/multipliers\n")
    L.append("#pragma once\n#include <stdint.h>\n")
    L.append("// ---- Sensor / window settings (must match the training data) ----")
    for k, v in [("MODEL_SAMPLE_RATE_HZ", C.SAMPLE_RATE_HZ), ("MODEL_WINDOW_SAMPLES", C.WINDOW_SAMPLES),
                 ("MODEL_N_CHANNELS", C.N_CHANNELS), ("MODEL_N_FEATURES", C.N_FEATURES),
                 ("MODEL_N_CLASSES", C.N_CLASSES), ("MODEL_PRETRIGGER_SAMPLES", C.PRETRIGGER_SAMPLES),
                 ("MODEL_COOLDOWN_MS", C.COOLDOWN_MS)]:
        L.append(f"#define {k} {v}")
    L.append(f"#define MODEL_TRIGGER_ACCEL_G {C.TRIGGER_ACCEL_G}f")
    L.append(f"#define MODEL_TRIGGER_GYRO_DPS {C.TRIGGER_GYRO_DPS}f\n")
    names = ", ".join(f'"{g}"' for g in C.GESTURES)
    L.append(f"static const char* const kGestureNames[MODEL_N_CLASSES] = {{ {names} }};\n")
    L.append("// ---- Normalization: feature = (raw - mean) / std, per channel ----")
    L.append(_c_array("float", "kChannelMean", data.channel_mean))
    L.append(_c_array("float", "kChannelStd", data.channel_std))

    L.append("// ---- Network shape ----")
    L.append(f"#define MODEL_N_LAYERS {n_layers}")
    L.append(f"#define MODEL_MAX_WIDTH {max(sizes[1:])}")
    L.append(f"static const int kLayerIn[MODEL_N_LAYERS] = {{ {', '.join(map(str, sizes[:-1]))} }};")
    L.append(f"static const int kLayerOut[MODEL_N_LAYERS] = {{ {', '.join(map(str, sizes[1:]))} }};\n")

    L.append("// ---- int8 model ----")
    L.append("// input:  x_q = clamp(round(feature / kInputScale) + kInputZeroPoint, -128, 127)")
    L.append("// layer:  acc = B[j] + sum_i W[j][i] * (x_q[i] - kInZeroPoint[l])")
    L.append("//         hidden: y_q = clamp(round(acc * M[j]) + kOutZeroPoint[l], kOutZeroPoint[l], 127)")
    L.append("//         last:   logit = acc * M[j]")
    L.append(f"static const float kInputScale = {_c_float(q['input_scale'])};")
    L.append(f"static const int32_t kInputZeroPoint = {q['input_zero_point']};")
    in_zp = [Ly["in_zero_point"] for Ly in q["layers"]]
    out_zp = [Ly.get("out_zero_point", 0) for Ly in q["layers"]]
    L.append(f"static const int32_t kInZeroPoint[MODEL_N_LAYERS] = {{ {', '.join(map(str, in_zp))} }};")
    L.append(f"static const int32_t kOutZeroPoint[MODEL_N_LAYERS] = {{ {', '.join(map(str, out_zp))} }};"
             "  // last entry unused\n")
    for i, Ly in enumerate(q["layers"]):
        L.append(f"// layer {i}: {sizes[i]} -> {sizes[i + 1]}")
        L.append(_c_array("int8_t", f"kW{i}_q", Ly["w_q"], per_line=20))
        L.append(_c_array("int32_t", f"kB{i}_q", Ly["b_q"]))
        L.append(_c_array("float", f"kM{i}", Ly["multiplier"]))
    refs = lambda prefix, suffix: ", ".join(f"{prefix}{i}{suffix}" for i in range(n_layers))
    L.append(f"static const int8_t* const kWeightsQ[MODEL_N_LAYERS] = {{ {refs('kW', '_q')} }};")
    L.append(f"static const int32_t* const kBiasesQ[MODEL_N_LAYERS] = {{ {refs('kB', '_q')} }};")
    L.append(f"static const float* const kMultipliers[MODEL_N_LAYERS] = {{ {refs('kM', '')} }};\n")

    L.append("// ---- float32 model (same network before quantization, for comparison) ----")
    for i, layer in enumerate(mlp.layers):
        L.append(_c_array("float", f"kW{i}_f", layer.weight.detach().numpy(), per_line=8))
        L.append(_c_array("float", f"kB{i}_f", layer.bias.detach().numpy(), per_line=8))
    L.append(f"static const float* const kWeightsF[MODEL_N_LAYERS] = {{ {refs('kW', '_f')} }};")
    L.append(f"static const float* const kBiasesF[MODEL_N_LAYERS] = {{ {refs('kB', '_f')} }};\n")

    L.append("// ---- Self-test: one recorded test gesture and the logits Python computed for it ----")
    L.append(f"static const int kTestLabel = {int(data.y_test[test_index])};  "
             f"// {C.GESTURES[int(data.y_test[test_index])]}")
    L.append(_c_array("float", "kTestWindow", test_raw, per_line=6))
    L.append(_c_array("float", "kTestLogitsInt8", test_logits_int8))
    L.append(_c_array("float", "kTestLogitsFloat", test_logits_float))

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L))
    return path


def check_with_host_compiler(qmodel: QuantMLP, data, header: str | Path | None = None) -> bool | None:
    """Compile the Arduino inference code (edge_nn.h + model_data.h) for *this*
    computer with g++, run it on every test gesture, and compare with Python.

    The int8 logits must be bit-identical to ``int8_forward``; the float logits
    must agree with PyTorch to ~1e-4. Returns None if g++ is not installed.
    """
    if shutil.which("g++") is None:
        print("g++ not found -- skipping the C++ check (the self-test on the board still runs).")
        return None
    header = Path(header or C.CLASSIFIER_SKETCH_DIR / "model_data.h")
    runner = C.ROOT / "tests" / "host_runner.cpp"
    # Build inside the project, not in the system temp folder: many managed Windows PCs
    # (AppLocker / antivirus rules) refuse to run programs from %TEMP% ("Access is denied").
    build_dir = C.ROOT / "build"
    build_dir.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=build_dir) as tmp:
        tmp = Path(tmp)
        # Copy both headers next to each other, so exactly this model_data.h is used.
        shutil.copy(C.CLASSIFIER_SKETCH_DIR / "edge_nn.h", tmp / "edge_nn.h")
        shutil.copy(header, tmp / "model_data.h")
        exe = tmp / ("runner.exe" if os.name == "nt" else "runner")
        subprocess.run(["g++", "-O2", "-std=c++14", "-I", str(tmp), str(runner), "-o", str(exe)],
                       check=True)
        raw = data.raw_test.astype(np.float32)
        raw.tofile(tmp / "in.bin")
        subprocess.run([str(exe), str(tmp / "in.bin"), str(tmp / "out.bin")], check=True)
        out = np.fromfile(tmp / "out.bin", dtype=np.float32).reshape(len(raw), 2, C.N_CLASSES)

    feats = np.stack([device_features(w, data.channel_mean, data.channel_std) for w in raw])
    ref_int8 = int8_forward(qmodel.to_int8(), feats)
    qmodel.mlp.eval()
    with torch.no_grad():
        ref_float = qmodel.mlp(torch.from_numpy(feats)).numpy()
    int8_same = int(np.all(out[:, 0] == ref_int8, axis=1).sum())
    float_diff = float(np.abs(out[:, 1] - ref_float).max())
    print(f"C++ int8  vs Python: {int8_same}/{len(raw)} test gestures bit-identical")
    print(f"C++ float vs PyTorch: largest logit difference {float_diff:.1e}")
    return int8_same == len(raw) and float_diff < 1e-3
